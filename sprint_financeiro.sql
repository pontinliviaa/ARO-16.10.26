-- SPRINT: RECEITAS, DESPESAS E TAXAS
-- Faça uma cópia do BANCO.FDB antes de executar.
-- Execute uma única vez, conectado ao banco existente, no IBExpert/FlameRobin.
-- As tabelas antigas não são apagadas ou renomeadas.

CREATE TABLE ARO_RECEITA (
    ID_REGISTRO INTEGER NOT NULL PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL,
    DESCRICAO VARCHAR(100) NOT NULL,
    VALOR NUMERIC(12,2) NOT NULL CHECK (VALOR > 0),
    DATA_MOVIMENTO DATE NOT NULL,
    CONSTRAINT FK_ARO_RECEITA_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE ARO_DESPESA (
    ID_REGISTRO INTEGER NOT NULL PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL,
    DESCRICAO VARCHAR(100) NOT NULL,
    VALOR NUMERIC(12,2) NOT NULL CHECK (VALOR > 0),
    DATA_MOVIMENTO DATE NOT NULL,
    CLASSIFICACAO VARCHAR(8) NOT NULL CHECK (CLASSIFICACAO IN ('Fixa', 'Variavel')),
    CONSTRAINT FK_ARO_DESPESA_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE ARO_TAXA (
    ID_TAXA INTEGER NOT NULL PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL,
    PERCENTUAL NUMERIC(5,2) NOT NULL CHECK (PERCENTUAL > 0 AND PERCENTUAL <= 100),
    DATA_REFERENCIA DATE DEFAULT CURRENT_DATE NOT NULL,
    CONSTRAINT UQ_ARO_TAXA_DATA UNIQUE (DATA_REFERENCIA),
    CONSTRAINT FK_ARO_TAXA_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE ARO_SALDO_MENSAL (
    ID_SALDO INTEGER NOT NULL PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL,
    ANO INTEGER NOT NULL CHECK (ANO BETWEEN 1 AND 9999),
    MES INTEGER NOT NULL CHECK (MES BETWEEN 1 AND 12),
    TOTAL_RECEITAS NUMERIC(18,2) NOT NULL,
    TOTAL_DESPESAS NUMERIC(18,2) NOT NULL,
    SALDO NUMERIC(18,2) NOT NULL,
    CONSTRAINT UQ_ARO_SALDO_MES UNIQUE (ID_USUARIO, ANO, MES),
    CONSTRAINT FK_ARO_SALDO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

-- Generators geram os IDs. Os triggers os colocam nos novos registros.
CREATE GENERATOR GEN_ARO_RECEITA;
CREATE GENERATOR GEN_ARO_DESPESA;
CREATE GENERATOR GEN_ARO_TAXA;
CREATE GENERATOR GEN_ARO_SALDO_MENSAL;

SET TERM ^ ;

CREATE TRIGGER BI_ARO_RECEITA FOR ARO_RECEITA
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID_REGISTRO IS NULL) THEN
        NEW.ID_REGISTRO = GEN_ID(GEN_ARO_RECEITA, 1);
END^

CREATE TRIGGER BI_ARO_DESPESA FOR ARO_DESPESA
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID_REGISTRO IS NULL) THEN
        NEW.ID_REGISTRO = GEN_ID(GEN_ARO_DESPESA, 1);
END^

CREATE TRIGGER BI_ARO_TAXA FOR ARO_TAXA
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID_TAXA IS NULL) THEN
        NEW.ID_TAXA = GEN_ID(GEN_ARO_TAXA, 1);
END^

CREATE TRIGGER BI_ARO_SALDO_MENSAL FOR ARO_SALDO_MENSAL
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID_SALDO IS NULL) THEN
        NEW.ID_SALDO = GEN_ID(GEN_ARO_SALDO_MENSAL, 1);
END^

-- Mesmo um INSERT direto no banco recebe a data atual na taxa.
CREATE TRIGGER BI_ARO_TAXA_DATA FOR ARO_TAXA
ACTIVE BEFORE INSERT POSITION 1
AS
BEGIN
    NEW.DATA_REFERENCIA = CURRENT_DATE;
END^

-- Na edição, a referência original da taxa é preservada.
CREATE TRIGGER BU_ARO_TAXA_DATA FOR ARO_TAXA
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    NEW.DATA_REFERENCIA = OLD.DATA_REFERENCIA;
END^

SET TERM ; ^
COMMIT;
